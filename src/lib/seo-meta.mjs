export function seoPluralIndex(count) {
 const n = Math.abs(count) % 100, last = n % 10;
 return n >= 11 && n <= 14 ? 2 : last === 1 ? 0 : last >= 2 && last <= 4 ? 1 : 2;
}
export function seoCountLabel(count, forms) { return String(count) + " " + forms[seoPluralIndex(count)]; }
export function seoYearRange(date = new Date()) {
 const year = Number(new Intl.DateTimeFormat("en-US", {timeZone:"Europe/Moscow",year:"numeric"}).format(date));
 return year + "-" + (year + 1);
}
